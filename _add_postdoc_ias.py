    t = vd['title']
    # 主 footer：含 "由 Trae Work 生成"（模块自带 footer 不含该字样）
    m = re.search(r'<footer>\s*[^<]*由 Trae Work 生成[^<]*(?:<[^>]+>[^<]*)*</footer>', c, re.S)
    if not m:
        print(f"  !! 未找到主 footer，{t}")
