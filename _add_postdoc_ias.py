def update_toc(c):
    """在 TOC 的 </ul>（nav 内）之前插入博士后与 IAS 区块（幂等）"""
    if '▸ 博士后水平进阶' in c[:60000]:
        return c
    # 定位 nav 内的 </ul>\n  </nav>
    m = re.search(r'(</ul>\s*\n\s*</nav>)', c)
    if not m:
        print("  !! 未找到 TOC 插入点")
        return c
    return c[:m.start(1)] + TOC_PD + TOC_IAS + c[m.start(1):]

def update_meta(c, t):
    """在 masthead meta 行追加模块说明（若尚无博士后字样）"""
    if '博士后水平进阶' in c:
        return c
    m = re.search(r'(<p class="meta">[^<]*)(</p>)', c)
    if not m:
        return c
    add = f' · 博士后进阶模块（PD1-PD6） · 高等研究所模块（IAS1-IAS5）'
    return c[:m.start(1)] + m.group(1) + add + c[m.start(2):]

