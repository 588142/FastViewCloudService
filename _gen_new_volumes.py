def chapters_to_html(chapters, vol):
    """将章节数据转换为 HTML 内容"""
    html_parts = []
    
    for ch in chapters:
        html_parts.append(f"""<section class="sec" id="{ch['id']}">
        <h2><span class="chapno">{" &middot; ".join(ch['title'].split(' · '))}</span></h2>""")
        
        # 内容
        if ch.get("content"):
            html_parts.append(ch["content"])
        
        # 思维导图
        if ch.get("diagram_code"):
            html_parts.append(f"""<figure class="diagram">
          <figcaption>{ch['diagram_title']}</figcaption>
          <pre class="mermaid">
{ch['diagram_code']}
          </pre>
        </figure>""")
        
        # 解释块
        for title, text in ch.get("explain_blocks", []):
            html_parts.append(f"""<div class="explain">
          <p><strong>{title}：</strong>{text}</p>
        </div>""")
        
        # 代表人物语录
        if ch.get("legacy_blocks"):
            html_parts.append('<h3>代表人物语录</h3>')
            for i in range(0, len(ch["legacy_blocks"]), 2):
                html_parts.append('<div class="legacy">')
                for name, quote, cite in ch["legacy_blocks"][i:i+2]:
                    html_parts.append(f"""<div>
            <div class="legacy-who">{name}</div>
            <blockquote>{quote}<cite>{cite}</cite></blockquote>
          </div>""")
                html_parts.append('</div>')
        
        html_parts.append('</section>')
    
    return '\n'.join(html_parts)

